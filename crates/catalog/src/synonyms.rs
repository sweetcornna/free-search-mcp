/// Pre-indexed lookup from tokenized/stemmed term → group indices.
pub(crate) struct SynonymMap {
    /// Each group's deduplicated stemmed/bigram tokens.
    groups: Vec<Vec<String>>,
    /// Inverted map from a token to the synonym groups it belongs to.
    by_token: HashMap<String, Vec<usize>>,
}

impl SynonymMap {
    pub(crate) fn build(tokenizer: &CatalogTokenizer) -> Self {
        let mut groups = Vec::with_capacity(SYNONYM_GROUPS.len());
        let mut by_token: HashMap<String, Vec<usize>> = HashMap::new();

        for (gid, raw_group) in SYNONYM_GROUPS.iter().enumerate() {
            let mut seen = HashSet::new();
            let mut group_tokens = Vec::new();
            for phrase in *raw_group {
                for (_, tok) in tokenizer.analyze_terms(phrase) {
                    if seen.insert(tok.clone()) {
                        by_token.entry(tok.clone()).or_default().push(gid);
                        group_tokens.push(tok);
                    }
                }
            }
            groups.push(group_tokens);
        }

        Self { groups, by_token }
    }

    /// Return synonym tokens for `token` (excluding `token` itself).
    pub(crate) fn expand(&self, token: &str) -> Vec<String> {
        let Some(gids) = self.by_token.get(token) else {
            return Vec::new();
        };
        let mut seen = HashSet::new();
        seen.insert(token);
        let mut out = Vec::new();
        for &gid in gids {
            for candidate in &self.groups[gid] {
                if seen.insert(candidate.as_str()) {
                    out.push(candidate.clone());
                }
            }
        }
        out
    }

    /// Number of synonym groups loaded (for tests/diagnostics).
    #[cfg(test)]
    pub(crate) fn group_count(&self) -> usize {
        self.groups.len()
    }
}
